import { useEffect, useMemo, useRef, useState } from "react";
import { ArrowUpRight } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  STOREFRONT_CATEGORIES,
  storefronts,
  previewUrl,
  type Storefront,
  type StorefrontCategory,
} from "@/data/storefronts";

const initials = (name: string) =>
  name
    .split(/\s+/)
    .map((w) => w[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();

function Preview({ s }: { s: Storefront }) {
  const [state, setState] = useState<"loading" | "ok" | "error">("loading");
  const ref = useRef<HTMLImageElement>(null);
  // The image may finish loading before hydration attaches onLoad/onError.
  useEffect(() => {
    const img = ref.current;
    if (img?.complete) setState(img.naturalWidth > 0 ? "ok" : "error");
  }, []);
  return (
    <div className="relative aspect-[3/2] overflow-hidden rounded-lg border border-border bg-card">
      {state === "loading" && (
        <div className="absolute inset-0 animate-pulse bg-secondary/60" aria-hidden="true" />
      )}
      {state === "error" ? (
        <div className="absolute inset-0 flex flex-col items-center justify-center gap-2 bg-secondary/40">
          <span className="font-mono text-3xl font-semibold text-muted-foreground" aria-hidden="true">
            {initials(s.name)}
          </span>
          <span className="text-xs text-muted-foreground">Preview unavailable</span>
        </div>
      ) : (
        <img
          ref={ref}
          src={previewUrl(s)}
          alt={`Homepage preview of the ${s.name} website`}
          loading="lazy"
          width={1200}
          height={800}
          onLoad={() => setState("ok")}
          onError={() => setState("error")}
          className={`h-full w-full object-cover object-top transition duration-700 group-hover:scale-[1.02] ${state === "ok" ? "opacity-100" : "opacity-0"}`}
        />
      )}
    </div>
  );
}

export function StorefrontShowcase() {
  const [cat, setCat] = useState<StorefrontCategory | "all">("all");
  const available = STOREFRONT_CATEGORIES.filter((c) =>
    storefronts.some((s) => s.categories.includes(c)),
  );
  const list = useMemo(
    () => (cat === "all" ? storefronts : storefronts.filter((s) => s.categories.includes(cat))),
    [cat],
  );
  return (
    <div>
      <div role="group" aria-label="Storefront category" className="flex flex-wrap gap-2 border-b border-border pb-5">
        {(["all", ...available] as const).map((c) => (
          <Button
            key={c}
            aria-pressed={cat === c}
            variant={cat === c ? "secondary" : "ghost"}
            onClick={() => setCat(c)}
            className={cat === c ? "text-primary" : "text-muted-foreground"}
          >
            {c === "all" ? "All Storefronts" : c}
          </Button>
        ))}
      </div>
      <p aria-live="polite" className="mt-4 text-sm text-muted-foreground">
        Showing {list.length} {list.length === 1 ? "storefront" : "storefronts"}
      </p>
      <ul className="mt-6 grid gap-x-8 gap-y-10 sm:grid-cols-2 lg:grid-cols-3">
        {list.map((s) => (
          <li key={s.slug} className="group flex min-w-0 flex-col">
            <Preview s={s} />
            <div className="flex flex-1 flex-col pt-5">
              <p className="font-mono text-[11px] uppercase tracking-wider text-shopify">
                {s.categories.join(" · ")}
              </p>
              <h3 className="mt-2 text-base font-semibold md:text-lg">{s.name}</h3>
              <p className="mt-2 flex-1 text-sm text-muted-foreground">{s.description}</p>
              <a
                href={s.url}
                target="_blank"
                rel="noopener noreferrer"
                className="mt-4 inline-flex items-center gap-1 self-start text-sm font-medium text-foreground hover:text-primary"
              >
                Visit Website
                <span className="sr-only"> for {s.name} (opens in a new tab)</span>
                <ArrowUpRight className="h-4 w-4" aria-hidden="true" />
              </a>
            </div>
          </li>
        ))}
      </ul>
      <p className="mt-12 border-t border-border pt-6 text-xs text-muted-foreground">
        All brand names, logos and websites belong to their respective owners. Previews are
        generated by a third-party capture service and may differ from the live site.
      </p>
    </div>
  );
}
